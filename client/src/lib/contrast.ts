// WCAG 2.x contrast ratio, as used by browser devtools and contrast checkers.

// Relative luminance of a #rrggbb color: each channel is converted from sRGB to
// linear light, then weighted by how sensitive the eye is to it.
export function relativeLuminance(hex: string): number {
  const channels = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const [r, g, b] = channels.map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

// 1 (same color) to 21 (black on white). AA for normal text needs at least 4.5.
export function contrastRatio(a: string, b: string): number {
  const [lighter, darker] = [relativeLuminance(a), relativeLuminance(b)].sort((x, y) => y - x);
  return (lighter + 0.05) / (darker + 0.05);
}
